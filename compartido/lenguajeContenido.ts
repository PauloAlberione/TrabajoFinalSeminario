export interface EleccionPregunta {
  id: string
  target: string
  prompt: string
  answer: string
  distractors: string[]
  tier: "direct" | "contextual"
  relation?: "synonym" | "antonym"
}

type PreguntaFila = [string, string, string, string, string, string, string, string]

function banco(prefijo: string, filas: PreguntaFila[]): EleccionPregunta[] {
  return filas.map(
    ([objetivo, consigna, respuesta, ...distractores], indice) => ({
      id: `${prefijo}-${indice}`,
      target: objetivo,
      prompt: consigna,
      answer: respuesta,
      distractors: distractores,
      tier: indice < 16 ? "direct" : "contextual",
    }),
  )
}

